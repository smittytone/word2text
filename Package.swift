// swift-tools-version: 5.10

import PackageDescription

/*
 This package definition was originally written to support CLI building of the word2text utility under Linux.
 This is because macOS users are expected to build using Xcode and the Xcode project files in this repository,
 and Linux users can't do this because (surprise, surprise) there's no Xcdoe for Linux.

 It has been updated to support the use of core files minus the host CLI code within third-party apps, currently
 macOS only. This is currently experimental.
 */

let package = Package(
    name: "word2text",
    platforms: [
        .macOS(.v12)
    ],
    products: [
        .library(name: "Word2text", targets: ["Word2text"]),
        .executable(name: "word2text", targets: ["word2text"])
    ],
    dependencies: [
        .package(url: "https://github.com/smittytone/clicore", from: "0.9.1"),
    ],
    targets: [
        .executableTarget(
            // Target data for the CLI tool
            name: "word2text",
            dependencies: [
                .product(name: "Clicore", package: "clicore")
            ],
            path: "word2text",
            exclude: [
                // `Info.plist` and `swift.plist` are not a Swift source files, so must be excluded
                // from macOS or Linux builds generated by calling the Swift compiler
                "Info.plist",
                "swift.plist",
                // This file is used solely by the library version
                "logging_lib.swift",
                // Use `gls word2text/lib | cat` to compile `lib/` list, which are aliases to the source
                // files used to build the library version
                "lib/constants.swift",
                "lib/convert_markdown.swift",
                "lib/convert_word.swift",
                "lib/document_to_markdown.swift",
                "lib/document_to_word.swift",
                "lib/entities.swift",
                "lib/extensions.swift",
                "lib/logging_lib.swift",
                "lib/markdown_to_document.swift",
                "lib/utilities.swift",
                "lib/word_to_document.swift"
            ],
            linkerSettings: [
                // Embed `swift.plist` into the __TEXT,__info_plist Mach-O section so the binary
                // can be signed and notarized. `.unsafeFlags` is fine here because `dlist` is
                // a top-level executable, not a library dependency.
                // macOS only: Linux has no Mach-O format and no notarization requirement.
                .unsafeFlags(
                    ["-Xlinker", "-sectcreate",
                     "-Xlinker", "__TEXT",
                     "-Xlinker", "__info_plist",
                     "-Xlinker", "word2text/swift.plist"],
                    .when(platforms: [.macOS])
                )
            ]
        ),
        .target(
            // Target for the library version
            name: "Word2text",
            path: "word2text/lib",
            sources: [
                // Just include the files needed for macOS lib usage
                // Get with `gls word2text/lib | cat`
                "constants.swift",
                "convert_markdown.swift",
                "convert_word.swift",
                "document_to_markdown.swift",
                "document_to_word.swift",
                "entities.swift",
                "extensions.swift",
                "logging_lib.swift",
                "markdown_to_document.swift",
                "utilities.swift",
                "word_to_document.swift"
            ]
        )
    ]
)
